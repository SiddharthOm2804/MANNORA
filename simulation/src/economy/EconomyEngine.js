import { MarketEngine } from './MarketEngine.js';
import { JobSystem } from './JobSystem.js';
import { FinanceSystem } from './FinanceSystem.js';
import { EventSystem } from '../events/EventSystem.js';

/**
 * EconomyEngine is the master coordinator for NEURAL CITY's civilization economy (Phase 6).
 *
 * Integrates:
 * - MarketEngine (supply, demand, dynamic commodity pricing, price elasticity)
 * - JobSystem (labor demand, job matching, salaries, unemployment)
 * - FinanceSystem (taxes, savings interest, business profit accounting, fiscal health)
 *
 * Simulates causal feedback:
 * Resource shortage → supply decreases → price increases → citizen spending changes
 * → business behavior changes → employment changes → economy changes.
 *
 * Computes simulation-grounded economic metrics:
 * - GDP-like production metric
 * - Unemployment rate
 * - Average income
 * - Average wealth
 * - Inflation
 * - Resource availability index
 * - Business count
 */
export class EconomyEngine {
  /**
   * @param {Object} [config]
   */
  constructor(config = {}) {
    this.marketEngine = new MarketEngine(config.market);
    this.jobSystem = new JobSystem(config.jobs);
    this.financeSystem = new FinanceSystem(config.finance);
    this.lastMetrics = null;
  }

  /**
   * Pipeline step: updates full economic cycle in worldState.
   *
   * @param {import('../core/WorldState.js').WorldState} worldState
   * @param {number} delta
   * @param {import('../core/RandomEngine.js').RandomEngine} random
   * @param {Object} [clockInfo={}]
   */
  update(worldState, delta, random, clockInfo = {}) {
    const pop = worldState.population;
    const econ = worldState.economy;
    const modifiers = EventSystem.getAggregateModifiers(worldState);
    const buildings = worldState.getBuildings();
    const agents = worldState.getAgents();

    // 1. UPDATE DYNAMIC COMMODITY PRICES VIA MARKET ENGINE (Supply & Demand feedback)
    const updatedMarketPrices = this.marketEngine.updatePrices(worldState, modifiers);

    // 2. AGGREGATE BUSINESS & COMMERCIAL ACTIVITY
    let businessCount = 0;
    let totalBusinessRevenue = 0;
    let totalBusinessCosts = 0;
    let totalBusinessProfit = 0;
    let totalBusinessTaxes = 0;
    let totalCommercialOutput = 0;

    for (const b of buildings) {
      if (b.type === 'commercial' || b.type === 'industrial') {
        businessCount++;
        const level = b.level || 1;
        const efficiency = b.efficiency || 1.0;
        const workers = b.workers || 1;

        // Base revenue generated by commercial operations
        const revenue = Number(((level * 45 * efficiency) + (workers * 8)).toFixed(2));
        const wages = Number((workers * 24 * efficiency).toFixed(2));
        const maintenance = (b.maintenanceCost || 12) * level;

        const balance = this.financeSystem.calculateBusinessBalance(
          b,
          revenue,
          wages,
          maintenance,
          econ.taxRate
        );

        totalBusinessRevenue += balance.revenue;
        totalBusinessCosts += balance.costs;
        totalBusinessProfit += balance.profit;
        totalBusinessTaxes += balance.taxPaid;
        totalCommercialOutput += revenue;

        // Store active balance on building descriptor
        b.revenue = balance.revenue;
        b.costs = balance.costs;
        b.profit = balance.profit;
        b.netProfit = balance.netProfit;
      }
    }

    // 3. LABOR MARKET & INCOME TELEMETRY (via JobSystem & Agents)
    let totalIncome = 0;
    let totalWealth = 0;
    let totalSavings = 0;
    let employedAgentCount = 0;
    const agentCount = agents.length;

    if (agentCount > 0) {
      for (const a of agents) {
        totalIncome += (a.income || 0);
        totalWealth += (a.wealth || 0);
        totalSavings += (a.savings || 0);
        if (a.employerId && a.occupation !== 'unemployed') {
          employedAgentCount++;
        }
      }
    } else {
      // Default estimation from macro population if individual agents aren't fully populated
      const workingPop = pop.demographics?.working || Math.round(pop.total * 0.65);
      employedAgentCount = pop.employed || Math.round(workingPop * 0.9);
      totalIncome = employedAgentCount * 30;
      totalWealth = pop.total * 120;
    }

    const averageIncome = agentCount > 0 ? Number((totalIncome / agentCount).toFixed(2)) : 30.0;
    const averageWealth = agentCount > 0 ? Number((totalWealth / agentCount).toFixed(2)) : 120.0;
    const averageSavings = agentCount > 0 ? Number((totalSavings / agentCount).toFixed(2)) : 15.0;

    // Unemployment telemetry
    const jobStats = this.jobSystem.getJobMarketTelemetry(worldState, agents);
    const activeUnemploymentRate = agentCount > 0
      ? Number(((agentCount - employedAgentCount) / agentCount).toFixed(3))
      : jobStats.unemploymentRate;

    // 4. TAX COLLECTION & MUNICIPAL BUDGET (via FinanceSystem)
    const baseWagesTax = Number((totalIncome * econ.taxRate).toFixed(2));
    const totalMunicipalIncome = Number(((baseWagesTax + totalBusinessTaxes) * (modifiers.gdpMultiplier || 1.0)).toFixed(2));

    // Municipal expenditures: civic overhead + building maintenance
    let civicExpenses = pop.total * 0.04;
    for (const b of buildings) {
      civicExpenses += (b.maintenanceCost || 10) * (b.level || 1);
    }
    civicExpenses = Number(civicExpenses.toFixed(2));

    const netMunicipalIncome = Number((totalMunicipalIncome - civicExpenses).toFixed(2));
    const newTreasury = Math.max(0, Number((econ.treasury + netMunicipalIncome).toFixed(2)));

    // 5. RESOURCE AVAILABILITY COMPOSITE INDEX (0 to 100)
    let totalResourceFills = 0;
    let resKeyCount = 0;
    const resourceKeys = ['energy', 'minerals', 'water', 'agriculture', 'technology', 'rawMaterials'];
    for (const rk of resourceKeys) {
      const res = worldState.resources[rk];
      if (res && res.max > 0) {
        totalResourceFills += Math.min(1.0, res.current / res.max);
        resKeyCount++;
      }
    }
    const resourceAvailability = resKeyCount > 0 ? Number(((totalResourceFills / resKeyCount) * 100).toFixed(1)) : 80.0;

    // 6. INFLATION AND GDP CALCULATIONS
    let inflationRate = econ.inflationRate || 0.02;
    // Price surge on essential resources drives inflation pressure
    const foodInflation = (updatedMarketPrices.agriculture / (this.marketEngine.basePrices.agriculture || 1.5)) - 1.0;
    const energyInflation = (updatedMarketPrices.energy / (this.marketEngine.basePrices.energy || 1.0)) - 1.0;
    const resourceInflationPressure = (foodInflation * 0.4 + energyInflation * 0.4) * 0.05;

    inflationRate = Math.max(-0.02, Math.min(0.20, Number((inflationRate * 0.95 + resourceInflationPressure + (modifiers.inflationDelta || 0)).toFixed(4))));

    // Simulation-grounded GDP-like Production Metric
    // Aggregates base production + business revenue + wage velocity + tech multiplier
    const techFactor = (worldState.resources.technology?.current || 1000) * 0.15;
    const baseEconomicCapacity = 60000;
    const calculatedGdp = Number((
      (baseEconomicCapacity + totalCommercialOutput * 12 + totalIncome * 4 + techFactor) *
      (modifiers.gdpMultiplier || 1.0)
    ).toFixed(2));

    // 7. ASSEMBLE COMPREHENSIVE ECONOMIC METRICS
    const economicMetrics = {
      gdp: calculatedGdp,
      unemployment: activeUnemploymentRate,
      unemploymentRate: activeUnemploymentRate,
      averageIncome,
      averageWealth,
      averageSavings,
      inflation: inflationRate,
      inflationRate,
      resourceAvailability,
      businessCount,
      businessStats: {
        totalRevenue: Number(totalBusinessRevenue.toFixed(2)),
        totalCosts: Number(totalBusinessCosts.toFixed(2)),
        totalProfit: Number(totalBusinessProfit.toFixed(2)),
        totalTaxesPaid: Number(totalBusinessTaxes.toFixed(2)),
      },
      treasury: newTreasury,
      income: totalMunicipalIncome,
      expenses: civicExpenses,
      netIncome: netMunicipalIncome,
      marketPrices: updatedMarketPrices,
      fiscalHealth: this.financeSystem.calculateFiscalHealth(newTreasury, totalMunicipalIncome, civicExpenses),
    };

    this.lastMetrics = economicMetrics;

    // 8. UPDATE WORLDSTATE (Economy & Global Metrics)
    worldState.updateEconomy({
      treasury: newTreasury,
      income: totalMunicipalIncome,
      expenses: civicExpenses,
      netIncome: netMunicipalIncome,
      gdp: calculatedGdp,
      inflationRate,
      marketPrices: updatedMarketPrices,
    });

    worldState.updatePopulation({
      unemploymentRate: activeUnemploymentRate,
      employed: employedAgentCount,
      unemployed: Math.max(0, (pop.total || agentCount) - employedAgentCount),
    });

    // Attach complete Phase 6 economic metrics to worldState.metrics
    worldState.metrics.gdp = calculatedGdp;
    worldState.metrics.unemployment = activeUnemploymentRate;
    worldState.metrics.unemploymentRate = activeUnemploymentRate;
    worldState.metrics.averageIncome = averageIncome;
    worldState.metrics.averageWealth = averageWealth;
    worldState.metrics.averageSavings = averageSavings;
    worldState.metrics.inflation = inflationRate;
    worldState.metrics.resourceAvailability = resourceAvailability;
    worldState.metrics.businessCount = businessCount;
    worldState.metrics.economicTelemetry = economicMetrics;
  }

  /**
   * Helper to retrieve latest computed economic metrics
   * @returns {Object|null}
   */
  getEconomicMetrics() {
    return this.lastMetrics;
  }
}

export default EconomyEngine;
