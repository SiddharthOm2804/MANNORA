import { SimulationEngine } from '../core/SimulationEngine.js';
import { WorldState } from '../core/WorldState.js';
import { StatisticalAnalysis } from './StatisticalAnalysis.js';

/**
 * ExperimentRunner executes single or multi-run simulation experiments with custom
 * starting conditions, parameter variations, seed schedules, and durations.
 */
export class ExperimentRunner {
  /**
   * @param {Object} [options]
   */
  constructor(options = {}) {
    this.options = options;
  }

  /**
   * Run a batch of simulation executions according to experiment specification.
   *
   * @param {Object} experimentSpec
   * @param {string} [experimentSpec.name] - Experiment label
   * @param {Object} experimentSpec.startingConditions - Base template world state or config
   * @param {Object} [experimentSpec.variables={}] - Key-value overrides or parameter sweeps
   * @param {number} [experimentSpec.durationDays=30] - Number of days to run each simulation
   * @param {number} [experimentSpec.ticksPerDay=1] - Discrete tick resolution per simulated day
   * @param {number} [experimentSpec.runs=10] - Number of independent simulation runs
   * @param {string} [experimentSpec.seedBehavior='incremental'] - 'fixed' | 'incremental' | 'random'
   * @param {number} [experimentSpec.baseSeed=42] - Starting seed
   * @param {Function} [onProgress] - Optional progress callback `(completed, total) => {}`
   * @returns {Promise<Object>} Complete experiment run bundle
   */
  async runExperiment(experimentSpec, onProgress = null) {
    const {
      id = `exp_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`,
      name = 'Untitled Experiment',
      description = '',
      startingConditions = {},
      variables = {},
      durationDays = 30,
      ticksPerDay = 1,
      runs = 10,
      seedBehavior = 'incremental',
      baseSeed = 42,
    } = experimentSpec;

    const totalTicks = Math.max(1, durationDays * ticksPerDay);
    const runResults = [];
    const eventCounts = {};

    const startTime = Date.now();

    for (let runIndex = 0; runIndex < runs; runIndex++) {
      // 1. Determine run seed
      let runSeed;
      if (seedBehavior === 'fixed') {
        runSeed = baseSeed;
      } else if (seedBehavior === 'random') {
        runSeed = Math.floor(Math.random() * 1000000000);
      } else {
        // incremental
        runSeed = baseSeed + runIndex * 137;
      }

      // 2. Clone and configure base state
      const worldState = this._createModifiedInitialState(startingConditions, variables, runIndex);

      // 3. Initialize isolated engine
      const engine = new SimulationEngine({
        seed: runSeed,
        tickRate: 10,
        maxHistory: 10,
      });

      engine.stateManager.restoreState(worldState);
      engine.clock.currentTick = worldState.tick || 0;
      engine.isInitialized = true;

      // Track events occurring in this specific run
      const runEvents = [];
      engine.on('event:triggered', (evt) => {
        const type = evt?.type || 'UNKNOWN';
        runEvents.push({ type, tick: engine.clock.currentTick, severity: evt?.severity });
        eventCounts[type] = (eventCounts[type] || 0) + 1;
      });

      // 4. Execute simulation run across duration
      for (let t = 0; t < totalTicks; t++) {
        engine.step();
      }

      // 5. Extract final outcome telemetry
      const finalState = engine.stateManager.getCurrentState();
      const outcome = this._extractRunOutcome(runIndex, runSeed, finalState, runEvents);
      runResults.push(outcome);

      if (onProgress && typeof onProgress === 'function') {
        onProgress(runIndex + 1, runs);
      }
    }

    const executionTimeMs = Date.now() - startTime;

    // 6. Aggregate multi-run statistics
    const aggregatedStats = this._aggregateOutcomes(runResults, runs, eventCounts);

    return {
      id,
      name,
      description,
      status: 'completed',
      spec: {
        startingConditions,
        variables,
        durationDays,
        ticksPerDay,
        totalTicks,
        runs,
        seedBehavior,
        baseSeed,
      },
      executionTimeMs,
      timestamp: new Date().toISOString(),
      runResults,
      aggregatedStats,
      disclaimer: 'SIMULATION RESULT: Outputs are synthetic statistical estimates generated by a mathematical model. They do not constitute real-world predictions or scientific certainty.',
    };
  }

  /**
   * Apply variable overrides to base template state.
   */
  _createModifiedInitialState(baseConditions, variables, runIndex) {
    let state;
    if (baseConditions instanceof WorldState) {
      state = baseConditions.clone();
    } else if (baseConditions && typeof baseConditions === 'object' && baseConditions.metrics) {
      state = WorldState.deserialize(baseConditions);
    } else {
      state = new WorldState({
        id: `world_exp_${runIndex}`,
        name: 'Experiment Model World',
        seed: 42,
      });
    }

    // Apply population override
    if (variables.population !== undefined) {
      const pop = Number(variables.population);
      state.metrics.population = pop;
      state.population.total = pop;
    } else if (baseConditions.population !== undefined) {
      const pop = Number(baseConditions.population);
      state.metrics.population = pop;
      state.population.total = pop;
    }

    // Apply starting resources override
    const resources = variables.resources || variables.startingResources || baseConditions.resources || {};
    for (const [key, val] of Object.entries(resources)) {
      if (state.resources[key] !== undefined) {
        state.resources[key] = Number(val);
      }
    }

    // Single resource shortcuts (e.g. waterAvailability: 500)
    if (variables.water !== undefined || variables.waterAvailability !== undefined) {
      state.resources.water = Number(variables.water ?? variables.waterAvailability);
    }
    if (variables.energy !== undefined || variables.energyAvailability !== undefined) {
      state.resources.energy = Number(variables.energy ?? variables.energyAvailability);
    }
    if (variables.food !== undefined || variables.foodAvailability !== undefined || variables.agriculture !== undefined) {
      state.resources.agriculture = Number(variables.food ?? variables.foodAvailability ?? variables.agriculture);
    }

    // Economy & Treasury overrides
    if (variables.treasury !== undefined || variables.startingMoney !== undefined) {
      const tr = Number(variables.treasury ?? variables.startingMoney);
      state.economy.treasury = tr;
      state.metrics.treasury = tr;
    }

    // Tax rate overrides
    if (variables.taxRate !== undefined) {
      state.government.taxRate = Number(variables.taxRate);
    }

    return state;
  }

  /**
   * Extract standardized telemetry record for one simulation run
   */
  _extractRunOutcome(runIndex, seed, finalState, runEvents) {
    const pop = finalState.population?.total ?? finalState.metrics?.population ?? 0;
    const health = finalState.population?.averageHealth ?? finalState.metrics?.health ?? 0;
    const happiness = finalState.population?.averageHappiness ?? finalState.metrics?.happiness ?? 0;
    const treasury = finalState.economy?.treasury ?? finalState.metrics?.treasury ?? 0;
    const gdp = finalState.economy?.gdp ?? 0;
    const unemployment = finalState.economy?.unemploymentRate ?? (1 - (finalState.economy?.employmentRate ?? 0.95));
    const water = finalState.resources?.water ?? 0;
    const energy = finalState.resources?.energy ?? 0;
    const agriculture = finalState.resources?.agriculture ?? 0;
    const approval = finalState.government?.civicApprovalScore ?? 75;
    const stability = finalState.metrics?.stability ?? 80;

    return {
      runIndex,
      seed,
      finalTick: finalState.tick,
      metrics: {
        population: Math.round(pop),
        health: Math.round(health * 10) / 10,
        happiness: Math.round(happiness * 10) / 10,
        treasury: Math.round(treasury),
        gdp: Math.round(gdp),
        unemployment: Math.round(unemployment * 1000) / 10, // as percentage
        water: Math.round(water),
        energy: Math.round(energy),
        agriculture: Math.round(agriculture),
        approval: Math.round(approval * 10) / 10,
        stability: Math.round(stability * 10) / 10,
      },
      eventsTriggered: runEvents.length,
      events: runEvents,
    };
  }

  /**
   * Aggregate across all run outcomes to compute distributions, variance, and event frequencies.
   */
  _aggregateOutcomes(runResults, totalRuns, eventCounts) {
    const metricKeys = [
      'population',
      'health',
      'happiness',
      'treasury',
      'gdp',
      'unemployment',
      'water',
      'energy',
      'agriculture',
      'approval',
      'stability',
    ];

    const metricsSummary = {};

    for (const key of metricKeys) {
      const series = runResults.map((r) => r.metrics[key]).filter((v) => typeof v === 'number' && !isNaN(v));
      metricsSummary[key] = StatisticalAnalysis.analyzeMetric(series, 8);
    }

    // Event frequency statistics
    const eventFrequencies = {};
    for (const [type, count] of Object.entries(eventCounts)) {
      eventFrequencies[type] = {
        totalOccurrences: count,
        frequencyPerRun: Math.round((count / totalRuns) * 100) / 100,
        percentageOfRuns: Math.min(100, Math.round((count / totalRuns) * 100)),
      };
    }

    return {
      totalRuns,
      metrics: metricsSummary,
      eventFrequencies,
    };
  }
}
