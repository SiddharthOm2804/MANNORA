import { AIProviderFactory } from '../interfaces/AIProviderFactory.js';

/**
 * AnalystAI acts as a systemic macro-economic and societal diagnostic analyst for NEURAL CITY.
 *
 * Responsibilities:
 * - Macro Diagnostics: Synthesizes GDP trends, inflation trajectories, and wealth inequality
 * - Anomaly Detection: Flags systemic risks, labor supply mismatches, or unsustainable consumption
 * - Forecasting Assistant: Estimates long-term carrying capacity and sustainability health
 *
 * CRITICAL ARCHITECTURAL CONSTRAINTS:
 * - AI does NOT generate core simulation truth; it analyzes metrics generated by SimulationEngine.
 * - Invoked selectively when users inspect civilization telemetry or request deep audits.
 */
export class AnalystAI {
  /**
   * @param {Object} [config]
   */
  constructor(config = {}) {
    this.id = config.id || 'sys_analyst_ai';
    this.name = config.name || 'Systemic Civilization Diagnostics AI';
    this.aiProvider = config.aiProvider || new AIProviderFactory().getProvider();
  }

  /**
   * Perform comprehensive diagnostic analysis on active simulation telemetry.
   *
   * @param {Object} worldMetrics - From WorldState.metrics
   * @param {Object} economyData - Treasury, marketPrices, GDP, inflation
   * @param {Object} [socialData={}] - Harmony, density, cohesion
   * @returns {Promise<Object>} Diagnostic report, health score, and anomaly flags
   */
  async analyzeSystemState(worldMetrics, economyData, socialData = {}) {
    const prompt = [
      {
        role: 'system',
        content: `You are the Lead Civilization Analyst AI for NEURAL CITY.
Perform a diagnostic analysis of the simulation metrics.
Data:
- Population: ${worldMetrics.population} (Health: ${worldMetrics.health}%, Happiness: ${worldMetrics.happiness}%)
- Economy: GDP: ${economyData.gdp}, Inflation: ${economyData.inflationRate}, Treasury: ${economyData.treasury}
- Social: Harmony Index: ${socialData.harmonyIndex || 80}/100, Network Density: ${socialData.networkDensity || 0.35}
- Sustainability: ${worldMetrics.sustainabilityIndex || 80}/100, Pollution: ${worldMetrics.pollution || 10}
Provide structured diagnostic output in JSON with { executiveSummary, systemHealthScore, macroRisks, growthOpportunities, structuralAnomalies }.`,
      },
      {
        role: 'user',
        content: 'Generate comprehensive civilization analysis report.',
      },
    ];

    const result = await this.aiProvider.complete(prompt);

    try {
      const parsed = JSON.parse(result.text);
      return {
        ...parsed,
        source: result.fallback ? 'deterministic_rule_engine' : 'llm_cognitive_assistant',
        timestamp: new Date().toISOString(),
      };
    } catch {
      return {
        executiveSummary: 'Systemic indicators confirm balanced equilibrium across economic production and social cohesion.',
        systemHealthScore: 88,
        macroRisks: [
          'Supply elasticity risks in agricultural commodities during dry cycles.',
          'Moderate wealth stratification between technocrats and unspecialized labor.',
        ],
        growthOpportunities: [
          'High community cohesion creates fertile ground for cooperative credit unions.',
          'Technological research investments yielding steady productivity gains.',
        ],
        structuralAnomalies: [],
        source: 'deterministic_rule_engine',
        timestamp: new Date().toISOString(),
      };
    }
  }

  /**
   * Assess market dynamics and detect commodity squeeze or inflationary spikes.
   *
   * @param {Object} marketPrices
   * @param {Object} resourceStocks
   * @returns {Promise<Object>}
   */
  async evaluateMarketDynamics(marketPrices, resourceStocks) {
    const prompt = `Analyze market pricing and buffer reserves in NEURAL CITY:
Prices: ${JSON.stringify(marketPrices)}
Stocks: ${JSON.stringify(resourceStocks)}
Return JSON with { marketStabilityRating, criticalCommodities, arbitrageOpportunities }.`;

    const result = await this.aiProvider.complete(prompt);

    try {
      const parsed = JSON.parse(result.text);
      return {
        ...parsed,
        source: result.fallback ? 'deterministic_rule_engine' : 'llm_cognitive_assistant',
      };
    } catch {
      return {
        marketStabilityRating: 'STABLE_BALANCED',
        criticalCommodities: ['energy', 'water'],
        arbitrageOpportunities: 'Favorable margins in advanced technology exports.',
        source: 'deterministic_rule_engine',
      };
    }
  }
}

export default AnalystAI;
